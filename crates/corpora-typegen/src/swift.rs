//! Swift emitter: `Enums.swift`, `Support.swift`, and one file per domain.
//!
//! All files belong to one `SwiftPM` target, so no cross-file imports are
//! needed. Structs are `Codable`, `Equatable` and `Sendable` with public
//! memberwise initializers; wire keys stay `snake_case` via `CodingKeys` to
//! match the Rust serialization. Decode timestamps with
//! `JSONDecoder.dateDecodingStrategy = .iso8601`.

use std::fmt::Write as _;

use crate::schema::{Domain, FieldType, Schema, TypeDef, TypeHome};

const CONFORMANCES: &str = "Codable, Equatable, Sendable";

fn header(schema: &Schema) -> String {
    format!(
        "// Generated by corpora-typegen from the schema v{}.\n\
         // Do not edit by hand; regenerate with `cargo run -p corpora-typegen`.\n\n\
         import Foundation\n",
        schema.version
    )
}

/// Render the schema as `(file name, content)` pairs: `Enums.swift`,
/// `Support.swift` and one `<Domain>.swift` per domain.
pub fn emit(schema: &Schema) -> Vec<(String, String)> {
    let mut files = vec![
        ("Enums.swift".to_owned(), emit_enums(schema)),
        ("Support.swift".to_owned(), emit_support(schema)),
    ];
    for (domain_name, domain) in &schema.domains {
        files.push((
            format!("{}.swift", pascal_case(domain_name)),
            emit_domain(schema, domain_name, domain),
        ));
    }
    files
}

fn emit_enums(schema: &Schema) -> String {
    let mut out = header(schema);
    let _ = writeln!(out);
    for (name, def) in &schema.enums {
        let _ = writeln!(out, "/// {}", def.description);
        let _ = writeln!(out, "public enum {name}: String, {CONFORMANCES} {{");
        for value in &def.values {
            let _ = writeln!(out, "    case {} = \"{value}\"", case_name(value));
        }
        let _ = writeln!(out, "}}\n");
    }
    out
}

/// `JSONValue`: the Swift mapping for the `Json` scalar.
fn emit_support(schema: &Schema) -> String {
    let mut out = header(schema);
    out.push_str(
        "\n/// Arbitrary JSON payload.\n\
         public enum JSONValue: Codable, Equatable, Sendable {\n\
         \x20   case null\n\
         \x20   case bool(Bool)\n\
         \x20   case number(Double)\n\
         \x20   case string(String)\n\
         \x20   case array([JSONValue])\n\
         \x20   case object([String: JSONValue])\n\
         \n\
         \x20   public init(from decoder: Decoder) throws {\n\
         \x20       let container = try decoder.singleValueContainer()\n\
         \x20       if container.decodeNil() {\n\
         \x20           self = .null\n\
         \x20       } else if let value = try? container.decode(Bool.self) {\n\
         \x20           self = .bool(value)\n\
         \x20       } else if let value = try? container.decode(Double.self) {\n\
         \x20           self = .number(value)\n\
         \x20       } else if let value = try? container.decode(String.self) {\n\
         \x20           self = .string(value)\n\
         \x20       } else if let value = try? container.decode([JSONValue].self) {\n\
         \x20           self = .array(value)\n\
         \x20       } else {\n\
         \x20           self = .object(try container.decode([String: JSONValue].self))\n\
         \x20       }\n\
         \x20   }\n\
         \n\
         \x20   public func encode(to encoder: Encoder) throws {\n\
         \x20       var container = encoder.singleValueContainer()\n\
         \x20       switch self {\n\
         \x20       case .null: try container.encodeNil()\n\
         \x20       case .bool(let value): try container.encode(value)\n\
         \x20       case .number(let value): try container.encode(value)\n\
         \x20       case .string(let value): try container.encode(value)\n\
         \x20       case .array(let value): try container.encode(value)\n\
         \x20       case .object(let value): try container.encode(value)\n\
         \x20       }\n\
         \x20   }\n\
         }\n",
    );
    out
}

fn emit_domain(schema: &Schema, domain_name: &str, domain: &Domain) -> String {
    let mut out = header(schema);
    let _ = writeln!(
        out,
        "//\n// Domain `{domain_name}`: {}\n",
        domain.description
    );

    for (union_name, union) in &schema.unions {
        if schema.type_home(union_name) == Some(TypeHome::Union(domain_name)) {
            emit_union(&mut out, union_name, union);
        }
    }

    for (type_name, type_def) in &domain.types {
        emit_struct(&mut out, schema, type_name, type_def);
    }
    out
}

/// A tagged union: enum with associated values, discriminated by `type`.
fn emit_union(out: &mut String, name: &str, union: &crate::schema::UnionDef) {
    let _ = writeln!(out, "/// {}", union.description);
    let _ = writeln!(out, "public enum {name}: {CONFORMANCES} {{");
    for variant in &union.variants {
        let _ = writeln!(out, "    case {}({variant})", case_name(variant));
    }
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    private enum CodingKeys: String, CodingKey {{ case type }}"
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "    public init(from decoder: Decoder) throws {{");
    let _ = writeln!(
        out,
        "        let container = try decoder.container(keyedBy: CodingKeys.self)"
    );
    let _ = writeln!(
        out,
        "        switch try container.decode(String.self, forKey: .type) {{"
    );
    for variant in &union.variants {
        let _ = writeln!(
            out,
            "        case \"{}\": self = .{}(try {variant}(from: decoder))",
            snake_case(variant),
            case_name(variant)
        );
    }
    let _ = writeln!(out, "        case let tag:");
    let _ = writeln!(
        out,
        "            throw DecodingError.dataCorruptedError(forKey: .type, in: container, debugDescription: \"unknown {name} type \\(tag)\")"
    );
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    let _ = writeln!(out, "    public func encode(to encoder: Encoder) throws {{");
    let _ = writeln!(
        out,
        "        var container = encoder.container(keyedBy: CodingKeys.self)"
    );
    let _ = writeln!(out, "        switch self {{");
    for variant in &union.variants {
        let _ = writeln!(out, "        case .{}(let value):", case_name(variant));
        let _ = writeln!(
            out,
            "            try container.encode(\"{}\", forKey: .type)",
            snake_case(variant)
        );
        let _ = writeln!(out, "            try value.encode(to: encoder)");
    }
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}\n");
}

fn emit_struct(out: &mut String, schema: &Schema, name: &str, def: &TypeDef) {
    // `extends` parents are flattened, matching the Rust emitter.
    let mut fields: Vec<(String, crate::schema::FieldDef)> = Vec::new();
    if let Some(parent) = def.extends.as_deref() {
        if let Some((_, parent_def)) = schema.find_type(parent) {
            fields.extend(
                parent_def
                    .fields()
                    .map(|(field_name, field)| (field_name.to_owned(), field)),
            );
        }
    }
    fields.extend(
        def.fields()
            .map(|(field_name, field)| (field_name.to_owned(), field)),
    );

    let _ = writeln!(out, "/// {}", def.description);
    let _ = writeln!(out, "public struct {name}: {CONFORMANCES} {{");

    for (field_name, field) in &fields {
        let _ = writeln!(out, "    /// {}", field.description);
        let property = escape_keyword(&camel_case(field_name));
        let ty = swift_type(schema, &FieldType::parse(&field.ty));
        let _ = writeln!(out, "    public var {property}: {ty}");
    }

    if fields.iter().any(|(field_name, field)| {
        camel_case(field_name) != field.wire_name.as_deref().unwrap_or(field_name)
    }) {
        let _ = writeln!(out);
        let _ = writeln!(out, "    private enum CodingKeys: String, CodingKey {{");
        for (field_name, field) in &fields {
            let property = escape_keyword(&camel_case(field_name));
            let wire_name = field.wire_name.as_deref().unwrap_or(field_name);
            if camel_case(field_name) == wire_name {
                let _ = writeln!(out, "        case {property}");
            } else {
                let _ = writeln!(out, "        case {property} = \"{wire_name}\"");
            }
        }
        let _ = writeln!(out, "    }}");
    }

    let _ = writeln!(out);
    let parameters = fields
        .iter()
        .map(|(field_name, field)| {
            let property = escape_keyword(&camel_case(field_name));
            let ty = swift_type(schema, &FieldType::parse(&field.ty));
            let default = if matches!(FieldType::parse(&field.ty), FieldType::Optional(_)) {
                " = nil"
            } else {
                ""
            };
            format!("{property}: {ty}{default}")
        })
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(out, "    public init({parameters}) {{");
    for (field_name, _) in &fields {
        let property = escape_keyword(&camel_case(field_name));
        let _ = writeln!(out, "        self.{property} = {property}");
    }
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}\n");
}

fn swift_type(schema: &Schema, ty: &FieldType) -> String {
    match ty {
        FieldType::Named(name) => match name.as_str() {
            "String" => "String".to_owned(),
            "bool" => "Bool".to_owned(),
            "i32" => "Int32".to_owned(),
            "i64" => "Int64".to_owned(),
            "u32" => "UInt32".to_owned(),
            "u64" => "UInt64".to_owned(),
            "f32" => "Float".to_owned(),
            "f64" => "Double".to_owned(),
            other => schema
                .scalars
                .get(other)
                .map_or_else(|| other.to_owned(), |scalar| scalar.swift.clone()),
        },
        FieldType::Optional(inner) => format!("{}?", swift_type(schema, inner)),
        FieldType::List(inner) => format!("[{}]", swift_type(schema, inner)),
        FieldType::Map(key, value) => format!(
            "[{}: {}]",
            swift_type(schema, key),
            swift_type(schema, value)
        ),
    }
}

/// `ready-for-review` -> `readyForReview`, `not reviewed` -> `notReviewed`,
/// `tf_zip` -> `tfZip`, `Section` -> `section`.
fn case_name(value: &str) -> String {
    let mut parts = value.split(['-', '_', ' ']).filter(|part| !part.is_empty());
    let mut out = parts.next().unwrap_or_default().to_owned();
    // Lowercase only the first character, preserving camelCase values.
    if let Some(first) = out.chars().next() {
        let lower: String = first.to_lowercase().collect();
        out.replace_range(..first.len_utf8(), &lower);
    }
    for part in parts {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    escape_keyword(&out)
}

/// `author_name` -> `authorName`.
fn camel_case(name: &str) -> String {
    let mut parts = name.split('_');
    let mut out = parts.next().unwrap_or_default().to_owned();
    for part in parts {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    out
}

/// `document` -> `Document`.
fn pascal_case(name: &str) -> String {
    let mut chars = name.chars();
    chars.next().map_or_else(String::new, |first| {
        first.to_uppercase().collect::<String>() + chars.as_str()
    })
}

/// `Section` -> `section` (union discriminator tags).
fn snake_case(name: &str) -> String {
    let mut out = String::new();
    for (index, ch) in name.chars().enumerate() {
        if ch.is_uppercase() {
            if index > 0 {
                out.push('_');
            }
            out.extend(ch.to_lowercase());
        } else {
            out.push(ch);
        }
    }
    out
}

fn escape_keyword(name: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "case",
        "class",
        "default",
        "enum",
        "extension",
        "import",
        "operator",
        "protocol",
        "return",
        "static",
        "struct",
        "subscript",
        "where",
    ];
    if KEYWORDS.contains(&name) {
        format!("`{name}`")
    } else {
        name.to_owned()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn case_name_should_camel_case_kebab_values() {
        assert_eq!(case_name("ready-for-review"), "readyForReview");
    }

    #[test]
    fn case_name_should_preserve_camel_case_values() {
        assert_eq!(case_name("protoCuneiform"), "protoCuneiform");
    }

    #[test]
    fn case_name_should_escape_keywords() {
        assert_eq!(case_name("default"), "`default`");
    }

    #[test]
    fn pascal_case_should_capitalize_domain_names() {
        assert_eq!(pascal_case("document"), "Document");
    }
}
