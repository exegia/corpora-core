//! SQL DDL emitter: Postgres `CREATE TABLE` statements for table-backed types.
//!
//! Value objects (`table: false`) never become tables; fields typed with them
//! are stored as `JSONB`. Enums become `TEXT` columns with `CHECK` constraints
//! so adding a value is an in-place migration rather than an `ALTER TYPE`.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::schema::{FieldDef, FieldType, Schema, TypeDef};

/// Render `CREATE TABLE` DDL for every table-backed type, in dependency order.
pub fn emit(schema: &Schema) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "-- Generated by corpora-typegen from schema/model.json v{}.\n\
         -- Do not edit by hand; regenerate with `cargo run -p corpora-typegen`.\n",
        schema.version
    );

    for (type_name, type_def, table) in ordered_tables(schema) {
        let _ = writeln!(out, "-- {}: {}", type_name, type_def.description);
        let _ = writeln!(out, "CREATE TABLE IF NOT EXISTS {table} (");

        let mut lines: Vec<String> = Vec::new();
        let mut primary_key: Vec<String> = Vec::new();

        for (field_name, field) in type_def.fields() {
            let parsed = FieldType::parse(&field.ty);
            let column = column_type(schema, &field, &parsed);
            let mut line = format!("    {field_name} {column}");
            if !matches!(parsed, FieldType::Optional(_)) {
                line.push_str(" NOT NULL");
            }
            if field.unique {
                line.push_str(" UNIQUE");
            }
            if let Some(default) = &field.default {
                let _ = write!(line, " DEFAULT {}", sql_literal(default));
            }
            if let Some(check) = enum_check(schema, field_name, &parsed) {
                line.push_str(&check);
            }
            if let Some(target) = &field.references {
                if let Some(reference) = foreign_key(schema, target) {
                    line.push_str(&reference);
                }
            }
            if field.primary_key {
                primary_key.push(field_name.to_owned());
            }
            lines.push(line);
        }

        if !primary_key.is_empty() {
            lines.push(format!("    PRIMARY KEY ({})", primary_key.join(", ")));
        }
        let _ = writeln!(out, "{}\n);\n", lines.join(",\n"));
    }
    out
}

/// Tables sorted so referenced tables are created before their dependents.
fn ordered_tables(schema: &Schema) -> Vec<(&str, &TypeDef, &str)> {
    let tables: BTreeMap<&str, (&TypeDef, &str)> = schema
        .domains
        .values()
        .flat_map(|domain| &domain.types)
        .filter_map(|(name, def)| def.table.name().map(|table| (name.as_str(), (def, table))))
        .collect();

    let mut ordered: Vec<(&str, &TypeDef, &str)> = Vec::new();
    let mut placed: Vec<&str> = Vec::new();
    // Simple fixed-point ordering; the schema is small and acyclic.
    while placed.len() < tables.len() {
        let before = placed.len();
        for (&name, &(def, table)) in &tables {
            if placed.contains(&name) {
                continue;
            }
            let ready = def.fields().all(|(_, field)| {
                field.references.as_deref().is_none_or(|target| {
                    let target_type = target.split('.').next().unwrap_or(target);
                    target_type == name
                        || !tables.contains_key(target_type)
                        || placed.contains(&target_type)
                })
            });
            if ready {
                placed.push(name);
                ordered.push((name, def, table));
            }
        }
        if placed.len() == before {
            // Cycle: append the rest in name order rather than loop forever.
            for (&name, &(def, table)) in &tables {
                if !placed.contains(&name) {
                    placed.push(name);
                    ordered.push((name, def, table));
                }
            }
        }
    }
    ordered
}

fn column_type(schema: &Schema, field: &FieldDef, ty: &FieldType) -> String {
    if let Some(sql_type) = &field.sql_type {
        return sql_type.clone();
    }
    match ty {
        FieldType::Named(name) => match name.as_str() {
            "String" => "TEXT".to_owned(),
            "bool" => "BOOLEAN".to_owned(),
            "i32" | "u32" => "INTEGER".to_owned(),
            "i64" | "u64" => "BIGINT".to_owned(),
            "f32" | "f64" => "DOUBLE PRECISION".to_owned(),
            other => schema.scalars.get(other).map_or_else(
                || {
                    if schema.enums.contains_key(other) {
                        "TEXT".to_owned()
                    } else {
                        // Embedded value object.
                        "JSONB".to_owned()
                    }
                },
                |scalar| scalar.sql.clone(),
            ),
        },
        FieldType::Optional(inner) => column_type(schema, field, inner),
        FieldType::List(inner) => match &**inner {
            FieldType::Named(name)
                if matches!(name.as_str(), "String") || schema.enums.contains_key(name) =>
            {
                "TEXT[]".to_owned()
            }
            _ => "JSONB".to_owned(),
        },
        FieldType::Map(..) => "JSONB".to_owned(),
    }
}

fn enum_check(schema: &Schema, column: &str, ty: &FieldType) -> Option<String> {
    let name = match ty {
        FieldType::Named(name) => name,
        FieldType::Optional(inner) => match &**inner {
            FieldType::Named(name) => name,
            _ => return None,
        },
        _ => return None,
    };
    let def = schema.enums.get(name)?;
    let values = def
        .values
        .iter()
        .map(|value| format!("'{value}'"))
        .collect::<Vec<_>>()
        .join(", ");
    Some(format!(" CHECK ({column} IN ({values}))"))
}

fn foreign_key(schema: &Schema, target: &str) -> Option<String> {
    let (type_name, column) = target.split_once('.')?;
    let (_, def) = schema.find_type(type_name)?;
    let table = def.table.name()?;
    Some(format!(" REFERENCES {table} ({column})"))
}

fn sql_literal(value: &serde_json::Value) -> String {
    match value {
        serde_json::Value::String(text) => format!("'{text}'"),
        other => other.to_string(),
    }
}
