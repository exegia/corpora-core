fn python_type(ty: &FieldType) -> anyhow::Result<String> {
    Ok(match ty {
        FieldType::Named(name) if name == "String" => "str".to_owned(),
        FieldType::Named(name) if name == "Json" => "Any".to_owned(),
        FieldType::Named(name) => anyhow::bail!("unsupported Python graph field type: {name}"),
        FieldType::Optional(inner) => format!("{} | None", python_type(inner)?),
        FieldType::List(inner) => format!("list[{}]", python_type(inner)?),
        FieldType::Map(key, value) => {
            format!("dict[{}, {}]", python_type(key)?, python_type(value)?)
        }
    })
}
