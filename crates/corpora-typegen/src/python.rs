//! Python output for reviewed shared API values and the canonical graph contract.

use std::fmt::Write as _;

use anyhow::ensure;

use crate::Schema;
use crate::schema::FieldType;

/// Emit a distributable, Pydantic-backed `TextRange` from the schema.
///
/// Other domain values remain outside this first Python slice until their
/// scalar and union mappings have been reviewed against existing bindings.
pub fn emit(schema: &Schema) -> anyhow::Result<Vec<(String, String)>> {
    let Some(range) = schema
        .domains
        .get("document")
        .and_then(|domain| domain.types.get("TextRange"))
    else {
        return Ok(Vec::new());
    };

    let mut document = format!(
        "# Generated by corpora-typegen from schema v{}. Do not edit.\n\
         from typing import Annotated\n\n\
         from pydantic import BaseModel, ConfigDict, Field\n\n\n\
         class TextRange(BaseModel):\n",
        schema.version
    );
    let _ = writeln!(
        document,
        "    {}",
        serde_json::to_string(&range.description)?
    );
    let _ = writeln!(
        document,
        "    model_config = ConfigDict(extra=\"ignore\")\n"
    );

    let mut names = Vec::new();
    for (name, field) in range.fields() {
        ensure!(field.ty == "u32", "TextRange.{name} must be u32");
        names.push(name.to_owned());
        let _ = writeln!(
            document,
            "    {name}: Annotated[\n        int,\n        Field(strict=True, ge=0, le=4294967295, description={}),\n    ]",
            serde_json::to_string(&field.description)?
        );
    }
    ensure!(
        names == ["start", "end"],
        "TextRange fields must be start and end"
    );

    let mut output = vec![
        (
            "src/corpora_schema_types/__init__.py".to_owned(),
            "# Generated by corpora-typegen. Do not edit.\nfrom .canonical_graph import CanonicalGraph, GraphValidationError, validate_graph\nfrom .document import TextRange\n\n__all__ = [\"CanonicalGraph\", \"GraphValidationError\", \"TextRange\", \"validate_graph\"]\n".to_owned(),
        ),
        (
            "src/corpora_schema_types/_version.py".to_owned(),
            format!(
                "# Generated by corpora-typegen. Do not edit.\n__version__ = {}\n",
                serde_json::to_string(&schema.version)?
            ),
        ),
        ("src/corpora_schema_types/document.py".to_owned(), document),
        ("src/corpora_schema_types/py.typed".to_owned(), String::new()),
    ];
    output.push((
        "src/corpora_schema_types/canonical_graph.py".to_owned(),
        emit_graph(schema)?,
    ));
    output.extend(emit_schemas());
    Ok(output)
}

fn emit_graph(schema: &Schema) -> anyhow::Result<String> {
    let graph = schema
        .domains
        .get("ingest")
        .and_then(|domain| domain.types.get("CanonicalGraph"))
        .ok_or_else(|| anyhow::anyhow!("ingest.CanonicalGraph is missing"))?;
    let mut graph_fields = String::new();
    for (name, field) in graph.fields() {
        let ty = python_type(&FieldType::parse(&field.ty))?;
        let alias = field.wire_name.as_deref();
        let optional = matches!(FieldType::parse(&field.ty), FieldType::Optional(_));
        let default = match (optional, alias) {
            (true, Some(alias)) => format!(
                " = Field(default=None, alias={})",
                serde_json::to_string(alias)?
            ),
            (true, None) => " = None".to_owned(),
            (false, Some(alias)) => format!(" = Field(alias={})", serde_json::to_string(alias)?),
            (false, None) => String::new(),
        };
        let _ = writeln!(graph_fields, "    {name}: {ty}{default}");
    }
    Ok(include_str!("../../../contracts/python/canonical_graph.py")
        .replace("    # <generated-fields>", graph_fields.trim_end()))
}

