//! Python output for the first shared value object used by the API.

use std::fmt::Write as _;

use anyhow::ensure;

use crate::Schema;

/// Emit a distributable, Pydantic-backed `TextRange` from the schema.
///
/// Other domain values remain outside this first Python slice until their
/// scalar and union mappings have been reviewed against existing bindings.
pub fn emit(schema: &Schema) -> anyhow::Result<Vec<(String, String)>> {
    let Some(range) = schema
        .domains
        .get("document")
        .and_then(|domain| domain.types.get("TextRange"))
    else {
        return Ok(Vec::new());
    };

    let mut document = format!(
        "# Generated by corpora-typegen from schema v{}. Do not edit.\n\
         from typing import Annotated\n\n\
         from pydantic import BaseModel, ConfigDict, Field\n\n\n\
         class TextRange(BaseModel):\n",
        schema.version
    );
    let _ = writeln!(
        document,
        "    {}",
        serde_json::to_string(&range.description)?
    );
    let _ = writeln!(
        document,
        "    model_config = ConfigDict(extra=\"ignore\")\n"
    );

    let mut names = Vec::new();
    for (name, field) in range.fields() {
        ensure!(field.ty == "u32", "TextRange.{name} must be u32");
        names.push(name.to_owned());
        let _ = writeln!(
            document,
            "    {name}: Annotated[\n        int,\n        Field(strict=True, ge=0, le=4294967295, description={}),\n    ]",
            serde_json::to_string(&field.description)?
        );
    }
    ensure!(
        names == ["start", "end"],
        "TextRange fields must be start and end"
    );

    Ok(vec![
        (
            "src/corpora_schema_types/__init__.py".to_owned(),
            "# Generated by corpora-typegen. Do not edit.\nfrom .document import TextRange\n\n__all__ = [\"TextRange\"]\n".to_owned(),
        ),
        (
            "src/corpora_schema_types/_version.py".to_owned(),
            format!(
                "# Generated by corpora-typegen. Do not edit.\n__version__ = {}\n",
                serde_json::to_string(&schema.version)?
            ),
        ),
        ("src/corpora_schema_types/document.py".to_owned(), document),
        ("src/corpora_schema_types/py.typed".to_owned(), String::new()),
    ])
}
